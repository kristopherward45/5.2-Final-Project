-- Q1: What is the total sales revenue and total profit generated by each product?
-- Author: Kristopher Ward
-- A1: Calculating total revenue and subtracting cost of goods to find profit per product.

SELECT 
    p.product_name,
    COUNT(o.order_id) AS total_orders,
    ROUND(SUM(o.price_usd), 2) AS total_revenue_usd,
    ROUND(SUM(o.price_usd - o.cogs_usd), 2) AS total_profit_usd
FROM orders o
JOIN products p ON o.primary_product_id = p.product_id
GROUP BY p.product_name
ORDER BY total_revenue_usd DESC;
GO


-- Q2: How many website sessions and total orders came from each marketing source?
-- Author: Kristopher Ward
-- A2: Left joining website sessions with orders to see session count vs total orders per source.

SELECT 
    ISNULL(ws.utm_source, 'direct / organic') AS utm_source,
    COUNT(DISTINCT ws.website_session_id) AS total_sessions,
    COUNT(DISTINCT o.order_id) AS total_orders
FROM website_sessions ws
LEFT JOIN orders o ON ws.website_session_id = o.website_session_id
GROUP BY ISNULL(ws.utm_source, 'direct / organic')
ORDER BY total_sessions DESC;
GO


-- Q3: What is the refund rate (percentage of items refunded) for each product?
-- Author: Kristopher Ward
-- A3: Comparing total items sold to total refunds to get a refund percentage.

SELECT 
    p.product_name,
    COUNT(oi.order_item_id) AS total_items_sold,
    COUNT(r.order_item_refund_id) AS total_refunds,
    ROUND(CAST(COUNT(r.order_item_refund_id) AS FLOAT) / COUNT(oi.order_item_id) * 100, 2) AS refund_rate_pct
FROM order_items oi
JOIN products p ON oi.product_id = p.product_id
LEFT JOIN order_item_refunds r ON oi.order_item_id = r.order_item_id
GROUP BY p.product_name
ORDER BY refund_rate_pct DESC;
GO


-- Q4: What are the top 5 most viewed website pages by total number of pageviews?
-- Author: Kristopher Ward
-- A4: Counting total pageviews per URL to find the top 5 pages on the site.

SELECT TOP 5
    pageview_url,
    COUNT(website_pageview_id) AS total_pageviews
FROM website_pageviews
GROUP BY pageview_url
ORDER BY total_pageviews DESC;
GO
