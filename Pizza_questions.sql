USE PizzaSales;
GO

-- Q1: What are the top 5 most ordered pizza types by total quantity sold?
-- Author: Etete
-- A1: Joining order details with pizzas and types to sum up quantities and get the top 5.

SELECT TOP 5
    pt.name AS pizza_type_name,
    SUM(od.quantity) AS total_quantity_sold
FROM order_details od
JOIN pizzas p ON od.pizza_id = p.pizza_id
JOIN pizza_types pt ON p.pizza_type_id = pt.pizza_type_id
GROUP BY pt.name
ORDER BY total_quantity_sold DESC;
GO


-- Q2: What is the total revenue generated by each pizza category?
-- Author: Kristopher Ward
-- A2: Multiplying price by quantity to find total sales revenue for each category.

SELECT 
    pt.category,
    ROUND(SUM(od.quantity * p.price), 2) AS total_revenue
FROM order_details od
JOIN pizzas p ON od.pizza_id = p.pizza_id
JOIN pizza_types pt ON p.pizza_type_id = pt.pizza_type_id
GROUP BY pt.category
ORDER BY total_revenue DESC;
GO


-- Q3: What is the average number of pizzas ordered per order?
-- Author: Kristopher Ward
-- A3: First getting total pizzas per order ID, then averaging those numbers.

SELECT 
    ROUND(AVG(CAST(sub.total_pizzas AS FLOAT)), 2) AS avg_pizzas_per_order
FROM (
    SELECT order_id, SUM(quantity) AS total_pizzas
    FROM order_details
    GROUP BY order_id
) sub;
GO


-- Q4: Which pizza size is ordered most frequently across all orders?
-- Author: Kristopher Ward
-- A4: Grouping total quantity sold by pizza size to see which size sells best.

SELECT 
    p.size,
    SUM(od.quantity) AS total_quantity_sold
FROM order_details od
JOIN pizzas p ON od.pizza_id = p.pizza_id
GROUP BY p.size
ORDER BY total_quantity_sold DESC;
GO

